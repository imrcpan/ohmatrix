#!/usr/bin/env tsx
/**
 * Reads the TOML locale files and generates TypeScript code.
 * Run this before typecheck or tests.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import toml from "@iarna/toml";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const root = resolve(__dirname, "..");
const localesDir = resolve(root, "locales");

// Parse languages.toml
interface LanguageDecl {
  id: string;
  label: string;
}

const languagesRaw = toml.parse(readFileSync(resolve(localesDir, "languages.toml"), "utf8"));
const languages = (languagesRaw as unknown as { language: LanguageDecl[] }).language;

// Parse each locale file
const catalogs = new Map<string, Record<string, string>>();
for (const lang of languages) {
  const filePath = resolve(localesDir, `${lang.id}.toml`);
  const parsed = toml.parse(readFileSync(filePath, "utf8")) as Record<string, string>;
  catalogs.set(lang.id, parsed);
}

// Generate TypeScript
const lines: string[] = ["/**", " * Generated from locales/*.toml by codegen.ts. Do not edit this file directly.", " */", ""];

// Export LANGUAGES
lines.push("export const LANGUAGES = [");
for (const lang of languages) {
  lines.push(`  { id: ${JSON.stringify(lang.id)}, label: ${JSON.stringify(lang.label)} },`);
}
lines.push("] as const;");
lines.push("");

// Export English catalog (as the source of keys for MessageKey)
const en = catalogs.get("en")!;
lines.push("export const en = {");
for (const [key, value] of Object.entries(en)) {
  lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
}
lines.push("};");
lines.push("");

// Export all other catalogs
for (const lang of languages) {
  if (lang.id === "en") continue;
  const catalog = catalogs.get(lang.id)!;
  const varName = lang.id.replace(/-/g, "_");
  lines.push(`const ${varName} = {`);
  for (const [key, value] of Object.entries(catalog)) {
    lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  }
  lines.push("};");
  lines.push("");
}

// Export catalogs map
lines.push("export const catalogs: Record<string, Record<string, string>> = {");
for (const lang of languages) {
  const varName = lang.id === "en" ? "en" : lang.id.replace(/-/g, "_");
  lines.push(`  ${JSON.stringify(lang.id)}: ${varName},`);
}
lines.push("};");

writeFileSync(resolve(__dirname, "generated.ts"), lines.join("\n") + "\n");
console.log(`Generated src/generated.ts from ${languages.length} locales (${Object.keys(en).length} keys each).`);
