// Generates OhMatrix.Core/Ui/Appearance/IconData.cs from the icons of the React Native app (src/packages/ui/src/Icon.tsx), so that the two
// draw the same shapes. Run it again after an icon is added or changed there:  node tools/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, "../../packages/ui/src/Icon.tsx"), "utf8");

const block = (start, end) => {
  const a = source.indexOf(start);
  const b = source.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error(`Icon.tsx no longer has ${start} ... ${end}`);
  return source.slice(a + start.length, b);
};

const paths = [...block("const PATHS = {", "} as const;").matchAll(/^ {2}(\w+):\s*\n?\s*"([^"]+)",/gm)].map((m) => [m[1], m[2]]);
const weights = [...block("const WEIGHT: Partial<Record<IconName, number>> = {", "};").matchAll(/(\w+):\s*([\d.]+)/g)];
const names = (start) => [...block(start, "]);").matchAll(/"(\w+)"/g)].map((m) => m[1]);
const solid = names("const SOLID: ReadonlySet<IconName> = new Set<IconName>([");
const fluent = names("const FLUENT: ReadonlySet<IconName> = new Set<IconName>([");
const fluentWeights = [...block("const FLUENT_WEIGHTS: Partial<Record<IconName, number>> = {", "};").matchAll(/(\w+):\s*([\d.]+)/g)];

if (paths.length < 50) throw new Error(`only ${paths.length} icons found: the format of Icon.tsx changed`);

const out = [];
out.push("// <auto-generated> by tools/gen-icons.mjs from src/packages/ui/src/Icon.tsx. Do not edit by hand. </auto-generated>");
out.push("namespace OhMatrix.Core.Ui.Appearance;", "");
out.push("/// <summary>The icons of the app: the paths (on a 24 by 24 grid) and how each is drawn.</summary>");
out.push("public static class IconData {");
out.push("    public static readonly IReadOnlyDictionary<string, string> Paths = new Dictionary<string, string> {");
// Avalonia takes the first control point of an `s` that follows a line as the reflection of the last curve's, which the spec only says for a curve before it; after a line that point is the current one, written out here (the bell's dome).
const plain = (d) => d.replace(/([hvl][-\d.\s,]*)s/g, "$1c0 0 ");
for (const [n, d] of paths) out.push(`        ["${n}"] = "${plain(d)}",`);
out.push("    };", "");
out.push("    /// <summary>Line weight of the icons that are not drawn with 2.</summary>");
out.push("    public static readonly IReadOnlyDictionary<string, double> Weight = new Dictionary<string, double> {");
for (const [, n, w] of weights) out.push(`        ["${n}"] = ${w},`);
out.push("    };", "");
out.push("    /// <summary>Solid glyphs: filled, with a line of 1.6 over them.</summary>");
out.push(`    public static readonly IReadOnlySet<string> Solid = new HashSet<string> { ${solid.map((n) => `"${n}"`).join(", ")} };`, "");
out.push("    /// <summary>Fluent System Icons: filled outlines, with a thin line of the same colour over them.</summary>");
out.push(`    public static readonly IReadOnlySet<string> Fluent = new HashSet<string> { ${fluent.map((n) => `"${n}"`).join(", ")} };`, "");
out.push("    /// <summary>The line over a Fluent icon, when it is not the usual 0.9 (the solid ones of the attach panel have none).</summary>");
out.push("    public static readonly IReadOnlyDictionary<string, double> FluentWeight = new Dictionary<string, double> {");
for (const [, n, w] of fluentWeights) out.push(`        ["${n}"] = ${w},`);
out.push("    };", "}", "");
writeFileSync(join(here, "../OhMatrix.Core/Ui/Appearance/IconData.cs"), out.join("\n"));
console.log(`${paths.length} icons, ${solid.length} solid, ${fluent.length} fluent`);
